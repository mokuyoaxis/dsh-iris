import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { useTempDshHome } from './test-env.js';
import { executeNetworkConfigCommand, readNetworkConfig } from '../lib/network-config-service.js';
import { executeConfigCommand } from '../lib/provider-config-service.js';
import { loadProviderCatalog, providerTaskBinding } from '../lib/provider-catalog.js';
import { wrapProviderCatalog, encodeProviderConfig } from '../lib/provider-config-format.js';
import { providerNetworkRequirement } from '../lib/network-policy.js';
import { createProviderNetworkManager } from '../lib/network-routing.js';
import { createConfiguredProviderAdapter } from '../lib/provider-adapters.js';
import { refreshModelDirectory } from '../lib/model-directory-service.js';
import { createConfiguredVisionModelPort } from '../lib/vision-model-routing.js';

const { root } = useTempDshHome('iris-network-bindings');
const v1 = path.join(root, 'v1.json'), v2 = path.join(root, 'v2.json'), source = path.join(root, 'providers.json'), wrapped = path.join(root, 'routed.json');
let originalFetch = globalThis.fetch, requests = 0;
globalThis.fetch = async () => { requests++; throw new Error('must stay offline'); };
const manager = createProviderNetworkManager({ networkConfigPath: v2 });
try {
  executeNetworkConfigCommand(v1, 'init');
  let state = executeNetworkConfigCommand(v1, 'show');
  executeNetworkConfigCommand(v1, 'pools.add', { expectedRevision: state.revision, pool: { id: 'explicit-direct', mode: 'fixed', candidates: [{ kind: 'direct' }] } });
  const oldBytes = fs.readFileSync(v1);
  state = executeNetworkConfigCommand(v2, 'routing.copy', { source: v1 });
  assert.equal(state.schemaVersion, 2); assert.notEqual(state.configId, JSON.parse(oldBytes).configId);
  assert.deepEqual(fs.readFileSync(v1), oldBytes); assert.deepEqual(state.bindings, []);
  const catalog = { providers: [{ id: 'p', enabled: true, mediaProtocol: 'openai-images', baseUrl: 'https://provider.invalid/v1', apiKey: 'fixture-private-key',
    models: [{ id: 'image', capabilities: ['image-gen', 'vision'] }] }], assignments: { 'image-gen': ['p::image'] }, preserve: { old: true } };
  fs.writeFileSync(source, JSON.stringify(catalog), { mode: 0o600 });
  const sourceBytes = fs.readFileSync(source);
  const requirement = { schemaVersion: 1, configId: state.configId, catalogId: crypto.randomUUID() };
  fs.writeFileSync(wrapped, JSON.stringify(encodeProviderConfig(wrapProviderCatalog(catalog, requirement))), { mode: 0o600 });
  const loaded = loadProviderCatalog(wrapped), provider = { ...loaded.providers[0] };
  assert.deepEqual(providerNetworkRequirement(provider), requirement);
  assert.equal(providerTaskBinding(provider), providerTaskBinding(catalog.providers[0]));
  assert.throws(() => createConfiguredProviderAdapter(provider), { code: 'IRIS_NETWORK_CONTEXT_REQUIRED' });
  await assert.rejects(refreshModelDirectory(provider, { force: true, save: () => true }), { code: 'IRIS_NETWORK_CONTEXT_REQUIRED' });
  assert.throws(() => createConfiguredVisionModelPort(provider, 'image'), { code: 'IRIS_NETWORK_CAPABILITY_UNSUPPORTED' });
  const first = await executeConfigCommand(wrapped, 'settings.show');
  await executeConfigCommand(wrapped, 'providers.set', { provider: { id: 'p', enabled: false } });
  assert.equal(JSON.parse(fs.readFileSync(wrapped)).schemaVersion, 1);
  assert.equal(JSON.parse(fs.readFileSync(wrapped)).catalog.preserve.old, true);
  assert.deepEqual(providerNetworkRequirement(loadProviderCatalog(wrapped)), requirement);
  await executeConfigCommand(wrapped, 'providers.set', { provider: { id: 'p', enabled: true } });
  assert.equal((await executeConfigCommand(wrapped, 'settings.show')).revision, first.revision);
  state = executeNetworkConfigCommand(v2, 'bindings.set', { expectedRevision: state.revision, catalogId: requirement.catalogId, providerId: 'p', poolId: 'explicit-direct' });
  assert.equal(state.bindings[0].poolId, 'explicit-direct');
  assert.throws(() => executeNetworkConfigCommand(v2, 'pools.remove', { expectedRevision: state.revision, id: 'explicit-direct', confirm: true }), { code: 'IRIS_NETWORK_CONFIG_IN_USE' });
  await assert.rejects(executeConfigCommand(wrapped, 'providers.remove', { provider_id: 'p' }, { resolveProviderNetwork: context => manager.resolveProviderNetwork(context) }), { code: 'IRIS_NETWORK_CONFIG_IN_USE' });
  const before = fs.readFileSync(v2);
  assert.throws(() => executeNetworkConfigCommand(v2, 'bindings.set', { expectedRevision: 'stale', catalogId: requirement.catalogId, providerId: 'p', poolId: 'explicit-direct' }), { code: 'IRIS_NETWORK_CONFIG_CHANGED' });
  assert.deepEqual(fs.readFileSync(v2), before);
  state = executeNetworkConfigCommand(v2, 'bindings.remove', { expectedRevision: state.revision, catalogId: requirement.catalogId, providerId: 'p', confirm: true });
  await executeConfigCommand(wrapped, 'providers.remove', { provider_id: 'p' }, { resolveProviderNetwork: context => manager.resolveProviderNetwork(context) });
  assert.equal(loadProviderCatalog(wrapped).providers.length, 0);
  const malformed = JSON.parse(fs.readFileSync(v2)); malformed.bindings.push({ catalogId: requirement.catalogId, providerId: 'p', poolId: 'missing' });
  const bad = path.join(root, 'invalid.json'); fs.writeFileSync(bad, JSON.stringify(malformed), { mode: 0o600 });
  assert.throws(() => readNetworkConfig(bad), { code: 'IRIS_NETWORK_CONFIG_INVALID' });
  assert.deepEqual(fs.readFileSync(source), sourceBytes); assert.equal(requests, 0);
  console.log('PASS network v2 bindings, protected pools/providers, envelope roundtrip and unchanged business binding, no silent uncovered requests');
} finally { globalThis.fetch = originalFetch; await manager.dispose(); }
