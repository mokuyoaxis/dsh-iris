import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { createEnvironment, businessId } from './environment.mjs';
import { setup } from './setup.mjs';
import { mcpProbe } from './mcp-probe.mjs';

const env = await createEnvironment(), checks = [];
const parsed = result => { assert(!result.isError, JSON.stringify(result)); return result.structuredContent ?? JSON.parse(result.content.find(item => item.type === 'text').text); };
try {
  const configBefore = await readFile(env.prepared.configPath);
  await assert.rejects(setup(env.prepared.directory), { code: 'EEXIST' });
  await assert.rejects(setup(env.templateRoot + '/private-demo'), /outside the plugin project/);
  assert.deepEqual(await readFile(env.prepared.configPath), configBefore);
  checks.push('setup rejects an existing directory without replacing its configuration');
  await env.start({ enabled: false });
  assert.equal((await env.http('/api/v0/connection-management/connections')).connections.length, 0);
  const call = env.request(); await env.submit(call, 403);
  checks.push('loading the package grants no connection access; a disabled business cannot execute');
  await env.close(); await env.start();
  const session = await env.http('/api/v0/session');
  assert.equal(session.workbenchMediaReadOnly, true);
  assert.equal(session.panelContributions.pages[0].dependency.pluginId, 'example.starter-board');
  assert.equal(session.panelContributions.renderers[0].id, 'example.starter-board.png');
  for (const item of [...session.panelContributions.pages, ...session.panelContributions.renderers]) {
    for (const route of [item.entry, ...item.styles]) assert.equal((await fetch(env.started.origin + route)).status, 200);
  }
  checks.push('the independent page and PNG renderer are actually served from selected, pinned package assets');
  const unselected = await env.connection([]);
  const without = await mcpProbe((await env.exported(unselected)).configuration);
  assert(!(await without.request('tools/list', {})).tools.some(item => item.name === 'iris_core_plugin_call'));
  const record = await env.connection(), config = (await env.exported(record)).configuration;
  let client = await mcpProbe(config);
  const names = (await client.request('tools/list', {})).tools.map(item => item.name);
  assert(names.includes('iris_core_plugin_call')); assert(!names.includes('iris_core_continue'));
  const catalog = parsed(await client.call('iris_core_plugin_catalog', {}));
  assert.equal(catalog.operations[0].id, businessId);
  const accepted = parsed(await client.call('iris_core_plugin_call', call));
  const operation = await env.terminal(accepted.operation.id); assert.equal(operation.state, 'succeeded', JSON.stringify(operation));
  assert.deepEqual(operation.sourceArtifactIds, env.prepared.artifactIds);
  const outputId = operation.result.artifactIds[0];
  const bytes = Buffer.from((await client.call('iris_core_image', { artifactId: outputId })).content.find(item => item.type === 'image').data, 'base64');
  assert.deepEqual([...bytes.subarray(0, 8)], [137, 80, 78, 71, 13, 10, 26, 10]);
  assert.equal(bytes.readUInt32BE(16), 292); assert.equal(bytes.readUInt32BE(20), 152);
  const digest = createHash('sha256').update(bytes).digest('hex');
  checks.push('a user-selected, business-only connection executes the real PNG operation through formal HTTP MCP');
  assert.equal(parsed(await client.call('iris_core_plugin_call', call)).operation.id, operation.id);
  await env.submit({ ...call, input: { ...call.input, columns: 1 } }, 409);
  checks.push('same UUID returns the saved Operation; changed input under that UUID is rejected');
  await env.close(); await env.start();
  assert.deepEqual((await env.exported(record)).configuration, config);
  client = await mcpProbe(config);
  assert.deepEqual(parsed(await client.call('iris_core_operation', { operationId: operation.id })).operation, operation);
  assert.equal(parsed(await client.call('iris_core_lookup', { key: call.key })).operation.id, operation.id);
  assert.equal((await env.http('/api/v0/plugin-operations/catalog')).artifacts.length, 3);
  const restored = Buffer.from((await client.call('iris_core_image', { artifactId: outputId })).content.find(item => item.type === 'image').data, 'base64');
  assert.deepEqual(restored, bytes);
  checks.push('restart preserves the original connection, UUID, exact Operation and PNG bytes without another business execution');
  await env.update(record, ['read']);
  client = await mcpProbe(config);
  assert(!(await client.request('tools/list', {})).tools.some(item => item.name === 'iris_core_plugin_call'));
  assert.equal(parsed(await client.call('iris_core_operation', { operationId: operation.id })).operation.state, 'succeeded');
  await assert.rejects(client.call('iris_core_plugin_call', { ...call, key: crypto.randomUUID() }), /Tool iris_core_plugin_call not found/);
  checks.push('reduced authority removes execution tools and rejects explicit calls while retaining granted history reads');
  await env.close(); await env.start({ version: '0.1.1' });
  await env.submit({ ...call, key: crypto.randomUUID() }, 409);
  assert.deepEqual((await env.http('/api/v0/operations/' + operation.id)).operation, operation);
  checks.push('a different installed version cannot replace a saved exact plugin dependency');
  await env.close(); await env.start({ present: false });
  assert.deepEqual((await env.http('/api/v0/operations/' + operation.id)).operation, operation);
  assert.deepEqual((await env.http('/api/v0/plugin-operations/catalog')).operations, []);
  assert.deepEqual(Buffer.from(await (await env.raw('/api/v0/artifacts/' + outputId + '/content')).arrayBuffer()), bytes);
  await env.submit({ ...call, key: crypto.randomUUID() }, 403);
  checks.push('missing implementation blocks new execution but keeps Core history and original artifact readable');
  console.log(JSON.stringify({ ok: true, checks, work: env.work, operationId: operation.id, artifactId: outputId, sha256: digest }, null, 2));
} finally { await env.close(); }
